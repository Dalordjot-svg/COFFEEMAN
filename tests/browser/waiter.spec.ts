import { expect, test, type Page } from '@playwright/test'
import { addProduct, chooseLatteModifiers, configureProduct, createTableOrder, itemAction, openCatalog, openLogin, signIn, tab } from './flows'

async function signOut(page: Page) {
  await tab(page, 'Профиль')
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page.getByLabel('Имя сотрудника')).toBeVisible()
}

test('сессия, оперативная панель, настройки, клавиатура и выход', async ({ page }) => {
  await openLogin(page)
  const name = page.getByLabel('Имя сотрудника')
  await name.click()
  await expect(name).toBeFocused()
  expect(Number.parseFloat(await name.evaluate(input => getComputedStyle(input).fontSize))).toBeGreaterThanOrEqual(16)
  const viewport = await page.locator('meta[name="viewport"]').getAttribute('content')
  expect(viewport).not.toMatch(/user-scalable\s*=\s*no|maximum-scale\s*=\s*1/)
  const screen = page.viewportSize()!
  await page.setViewportSize({ ...screen, height: screen.height - 300 })
  await expect(name).toBeInViewport()
  await page.setViewportSize(screen)
  await name.fill('Паша')
  await name.press('Enter')
  await expect(page.getByRole('heading', { name: 'Главная' })).toBeVisible()
  await expect(page.getByText(/Паша/).first()).toBeVisible()
  await expect(page.getByText('Требуют внимания', { exact: true })).toBeVisible()
  await expect(page.getByText(/Готовится дольше|дольше нормы|ждёт выдачи|ожидает выдачи/i).first()).toBeVisible()

  await page.reload()
  await expect(page.getByRole('heading', { name: 'Главная' })).toBeVisible()
  await tab(page, 'Профиль')
  await expect(page.getByRole('heading', { name: 'Профиль' })).toBeVisible()
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Настройки' })).toBeVisible()
  const audio = page.getByRole('switch', { name: 'Звуковые уведомления' }).or(page.getByRole('checkbox', { name: 'Звуковые уведомления' }))
  const enabled = await audio.isChecked()
  await audio.click()
  if (enabled) await expect(audio).not.toBeChecked()
  else await expect(audio).toBeChecked()
  await page.reload()
  await tab(page, 'Профиль')
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  if (enabled) await expect(audio).not.toBeChecked()
  else await expect(audio).toBeChecked()
  await signOut(page)
  await page.reload()
  await expect(name).toBeVisible()
})

test('заказ с несколькими гостями, модификаторы, дозаказ и завершение', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-26T12:48:00Z'))
  await signIn(page)
  const sales = page.getByText('Мои продажи', { exact: true }).locator('..').locator('strong')
  const amount = (text: string) => Number(text.replace(/[^\d,]/g, '').replace(',', '.'))
  await expect.poll(async () => amount(await sales.innerText())).toBeGreaterThan(0)
  const previousSales = amount(await sales.innerText())
  await createTableOrder(page, 12, 2)
  await page.getByRole('button', { name: 'Добавить гостя', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Добавить позицию гостю 3', exact: true })).toBeVisible()
  await openCatalog(page)
  await configureProduct(page, 'Латте')
  const product = page.getByRole('dialog')
  await chooseLatteModifiers(page)
  await product.getByRole('button', { name: 'Увеличить количество' }).click()
  await expect(product.getByRole('button', { name: /Добавить.*440/ })).toBeEnabled()
  await expect(product.getByLabel('Количество', { exact: true })).toHaveValue('2')
  const comment = product.getByRole('textbox', { name: /Комментарий/ })
  await comment.fill('Подать вместе')
  await product.getByRole('button', { name: /^Добавить/ }).click()
  await expect(product).toHaveCount(0)
  await page.getByRole('button', { name: 'Закрыть меню', exact: true }).click()
  await expect(page.getByText(/Ваниль/).first()).toBeVisible()
  await expect(page.getByText('Подать вместе', { exact: true })).toBeVisible()

  await addProduct(page, 'Чизкейк', 2)
  await page.getByRole('button', { name: /Латте/ }).click()
  await product.getByRole('combobox', { name: 'Гость', exact: true }).selectOption({ label: 'Гость 3' })
  await product.getByRole('button', { name: /^Сохранить/ }).click()
  await expect(product).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Гость 3', exact: true }).getByText('Латте', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Удалить гостя 1', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Гость 3', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Отправить на кухню', exact: true }).click()
  await itemAction(page, 'Латте', 'Отметить готовым')
  await itemAction(page, 'Латте', 'Отметить выданным')
  await itemAction(page, 'Чизкейк', 'Отметить готовым')
  await itemAction(page, 'Чизкейк', 'Отметить выданным')
  await addProduct(page, 'Капучино')
  await page.getByRole('button', { name: 'Отправить на кухню', exact: true }).click()
  await itemAction(page, 'Капучино', 'Отметить готовым')
  await page.getByRole('dialog').getByRole('button', { name: 'Закрыть', exact: true }).click()
  const cappuccino = page.getByRole('button', { name: /Капучино/ })
  await cappuccino.dblclick({ delay: 40 })
  await expect(cappuccino).toContainText('Выдано')
  await page.getByRole('button', { name: 'К расчёту', exact: true }).click()
  const checkout = page.getByRole('dialog', { name: 'Позиции для кассы' })
  await expect(checkout).toContainText('Капучино')
  const thumb = checkout.getByRole('button', { name: 'Закрыть заказ' })
  await thumb.click()
  await expect(checkout).toBeVisible()
  const knob = (await thumb.boundingBox())!
  const track = (await thumb.locator('..').boundingBox())!
  await page.mouse.move(knob.x + knob.width / 2, knob.y + knob.height / 2)
  await page.mouse.down()
  await page.mouse.move(track.x + track.width - knob.width / 2, knob.y + knob.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(checkout).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'К расчёту', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Выберите стол', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await tab(page, 'Главная')
  await expect.poll(async () => amount(await sales.innerText())).toBe(previousSales + 1005)
  await tab(page, 'Профиль')
  await page.getByRole('button', { name: 'История заказов', exact: true }).click()
  await expect(page.getByRole('button', { name: /Стол 12.*1\s?005/ })).toBeVisible()
})

test('PWA устанавливается и загружает сохранённую сессию после потери сети', async ({ page, context }) => {
  test.skip(process.env.QA_PREVIEW !== '1', 'Проверка service worker требует production-сборку')
  await signIn(page)
  await expect(page.getByRole('heading', { name: 'Главная' })).toBeVisible()
  const manifestUrl = await page.locator('link[rel="manifest"]').getAttribute('href')
  expect(manifestUrl).toBeTruthy()
  const manifest = await (await page.request.get(manifestUrl!)).json()
  expect(manifest.name).toMatch(/COFFEEMAN/)
  expect(manifest.display).toBe('standalone')
  expect(manifest.icons.map((entry: { sizes: string }) => entry.sizes)).toEqual(expect.arrayContaining(['192x192', '512x512']))
  await page.waitForFunction(() => Boolean(navigator.serviceWorker?.controller))
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Главная' })).toBeVisible()
  await tab(page, 'Заказы')
  await expect(page.getByRole('heading', { name: 'Заказы' })).toBeVisible()
  await context.setOffline(false)
  await expect.poll(() => page.evaluate(() => navigator.onLine)).toBe(true)
})
